    private void jTableNCCMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_jTableNCCMouseClicked
// 1. Lấy vị trí dòng mà Đạt vừa bấm chuột vào
int row = jTableNCC.getSelectedRow();

if (row >= 0) {
    // 1. Lấy mã Nhà cung cấp (Cột 0: maNCC) để hiển thị ảnh
    String maNCC = jTableNCC.getValueAt(row, 0).toString();
    
    // Đường dẫn ảnh NCC
    String path = "src/images_ncc/" + maNCC + ".jpg";
    
    // Gọi hàm hiển thị lên jLabel7
    updateImageNCC(path);
    
    // 2. Đổ dữ liệu từ bảng lên các ô nhập liệu (Sửa chỉ số cột tại đây)
    txtMaNCC.setText(jTableNCC.getValueAt(row, 0).toString());  // Cột 0: maNCC
    txtTenNCC.setText(jTableNCC.getValueAt(row, 1).toString()); // Cột 1: tenNCC

    // ĐỔI LẠI VỊ TRÍ CỘT 2 VÀ 3:
    // Cột 3 trên bảng là Địa chỉ (TP. Hồ Chí Minh, Bắc Ninh...)
    txtDiaChi.setText(jTableNCC.getValueAt(row, 2).toString());
    
    // Cột 2 trên bảng là Số điện thoại (0903..., 0983...)
    txtSDT.setText(jTableNCC.getValueAt(row, 3).toString());

    // Cột 4 là Loại hàng đưa vào ComboBox
    cbLoaiHang.setSelectedItem(jTableNCC.getValueAt(row, 4).toString());
}       // TODO add your handling code here:
    }//GEN-LAST:event_jTableNCCMouseClicked

