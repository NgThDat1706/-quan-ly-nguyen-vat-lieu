    public void updateImageNCC(String imagePath) {
        if (imagePath == null || imagePath.isEmpty()) {
            jLabel7.setIcon(null);
            jLabel7.setText("No Image");
            return;
        }
        try {
            ImageIcon myImage = new ImageIcon(imagePath);
            Image img = myImage.getImage();

            // Lấy kích thước của jLabel7 để scale ảnh
            int width = jLabel7.getWidth() > 0 ? jLabel7.getWidth() : 180;
            int height = jLabel7.getHeight() > 0 ? jLabel7.getHeight() : 180;

            Image newImg = img.getScaledInstance(width, height, Image.SCALE_SMOOTH);
            jLabel7.setIcon(new ImageIcon(newImg));
            jLabel7.setText("");
        } catch (Exception e) {
            jLabel7.setIcon(null);
            System.out.println("Lỗi load ảnh NCC: " + e.getMessage());
        }
    }
