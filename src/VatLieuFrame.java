    private void btnTimKiemActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnTimKiemActionPerformed
        try {
            // 1. Lấy nội dung cần tìm (xóa khoảng trắng thừa)
            String input = txtTimKiem.getText().trim();

            // 2. Kết nối CSDL
            Connection conn = new DBContext().getConnection();

            // 3. Câu lệnh SQL tìm kiếm theo Mã hoặc Tên (dùng LIKE để tìm gần đúng)
            // Dấu N'?' dùng để hỗ trợ tìm tiếng Việt có dấu
            String sql = "SELECT * FROM NGUYEN_VAT_LIEU WHERE maNVL LIKE ? OR tenNVL LIKE ?";

            PreparedStatement pstmt = conn.prepareStatement(sql);
            pstmt.setString(1, "%" + input + "%"); // % giúp tìm chữ nằm ở bất kỳ đâu
            pstmt.setString(2, "%" + input + "%");

            ResultSet rs = pstmt.executeQuery();

            // 4. Xóa bảng cũ và nạp kết quả tìm thấy vào bảng màu xanh
            model = (DefaultTableModel) tblVatLieu.getModel();
            model.setRowCount(0);

            while (rs.next()) {
                model.addRow(new Object[]{
                    rs.getString("maNVL"),
                    rs.getString("tenNVL"),
                    rs.getString("loaiNVL"),
                    rs.getInt("soLuong"),
                    rs.getFloat("donGia")
                });
            }

            conn.close();

            // Nếu không tìm thấy gì thì báo nhẹ một câu
            if (model.getRowCount() == 0) {
                JOptionPane.showMessageDialog(this, "Không tìm thấy nguyên vật liệu nào khớp!");
            }

        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Lỗi tìm kiếm: " + e.getMessage());
        }        // TODO add your handling code here:
    }//GEN-LAST:event_btnTimKiemActionPerformed

