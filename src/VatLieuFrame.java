    private void btnThemActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnThemActionPerformed

        try {
            // 1. Phải đảm bảo model đã được khởi tạo (Sửa lỗi Null)
            if (model == null) {
                model = (DefaultTableModel) tblVatLieu.getModel();
            }

            // 2. Kết nối CSDL từ DBContext của bạn
            Connection conn = new DBContext().getConnection();

            // 3. Câu lệnh SQL Insert chuẩn theo bảng NGUYEN_VAT_LIEU
            String sql = "INSERT INTO NGUYEN_VAT_LIEU (maNVL, tenNVL, loaiNVL, soLuong, donGia) VALUES (?, ?, ?, ?, ?)";
            PreparedStatement pstmt = conn.prepareStatement(sql);

            // 4. Lấy dữ liệu từ các ô nhập liệu
            pstmt.setString(1, txtMaNVL.getText());
            pstmt.setString(2, txtTenNVL.getText());
            pstmt.setString(3, cboLoaiNVL.getSelectedItem().toString());
            pstmt.setInt(4, Integer.parseInt(txtSoLuong.getText()));
            pstmt.setFloat(5, Float.parseFloat(txtdonGia.getText()));

            // 5. Thực thi và nạp lại bảng
            pstmt.executeUpdate();
            conn.close();

            loadDataToTable(); // Gọi hàm này để cập nhật bảng màu Cyan
            clearForm();       // THÊM DÒNG NÀY Ở ĐÂY để xóa trắng các ô nhập liệu
            JOptionPane.showMessageDialog(this, "Thêm mới thành công!");

        } catch (NumberFormatException ex) {
            JOptionPane.showMessageDialog(this, "Số lượng và Đơn giá phải là số!");
        } catch (Exception e) {
            // Bắt lỗi trùng khóa chính (HW10...)
            if (e.getMessage().contains("PRIMARY KEY")) {
                JOptionPane.showMessageDialog(this, "Mã này đã tồn tại, vui lòng nhập mã khác!");
            } else {
                JOptionPane.showMessageDialog(this, "Lỗi: " + e.getMessage());
            }

        }     // TODO add your handling code here:
    }//GEN-LAST:event_btnThemActionPerformed

    private void btnXoaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnXoaActionPerformed
        try {
            // 1. Kết nối DB
            Connection conn = new DBContext().getConnection();

            // 2. Lấy mã NVL từ ô nhập liệu để biết xóa dòng nào
            String ma = txtMaNVL.getText();

            // Kiểm tra xem người dùng đã nhập/chọn mã chưa
            if (ma.equals("")) {
                JOptionPane.showMessageDialog(this, "Vui lòng chọn hoặc nhập mã NVL cần xóa!");
                return;
            }

            // 3. Hỏi xác nhận trước khi xóa cho chắc ăn
            int confirm = JOptionPane.showConfirmDialog(this, "Bạn có chắc muốn xóa nguyên vật liệu này?", "Xác nhận", JOptionPane.YES_NO_OPTION);

            if (confirm == JOptionPane.YES_OPTION) {
                String sql = "DELETE FROM NGUYEN_VAT_LIEU WHERE maNVL = ?";
                PreparedStatement pstmt = conn.prepareStatement(sql);
                pstmt.setString(1, ma);

                pstmt.executeUpdate();

                // 4. Cập nhật lại bảng và xóa trắng form
                loadDataToTable();
                txtMaNVL.setText("");
                txtTenNVL.setText("");
                txtSoLuong.setText("");
                txtdonGia.setText("");

                JOptionPane.showMessageDialog(this, "Đã xóa thành công!");
            }
            conn.close();
 clearForm(); //Thêm dòng này vào đây để xóa trắng các ô
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Lỗi xóa: " + e.getMessage());
        }        // TODO add your handling code here:
    }//GEN-LAST:event_btnXoaActionPerformed

