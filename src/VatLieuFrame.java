    public void loadDataToTable() {
        model = (DefaultTableModel) tblVatLieu.getModel();
        model.setRowCount(0);
        try {
            // Sử dụng DBContext của bạn
            Connection conn = new DBContext().getConnection();
            String sql = "SELECT * FROM NGUYEN_VAT_LIEU";
            Statement st = conn.createStatement();
            ResultSet rs = st.executeQuery(sql);

            while (rs.next()) {
                model.addRow(new Object[]{
                    rs.getString("maNVL"),
                    rs.getString("tenNVL"),
                    rs.getString("loaiNVL"),
                    rs.getInt("soLuong"),
                    rs.getFloat("donGia")
                });
            }
            conn.close();
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Lỗi nạp dữ liệu: " + e.getMessage());
        }
    }

