    public void filterByLoai(String loai) {
        model = (DefaultTableModel) tblVatLieu.getModel();
        model.setRowCount(0);
        try {
            Connection conn = new DBContext().getConnection();
            String sql;
            if (loai.equals("Tất cả")) {
                sql = "SELECT * FROM NGUYEN_VAT_LIEU";
            } else {
                sql = "SELECT * FROM NGUYEN_VAT_LIEU WHERE loaiNVL = ?";
            }

            PreparedStatement pstmt = conn.prepareStatement(sql);
            if (!loai.equals("Tất cả")) {
                pstmt.setString(1, loai);
            }

            ResultSet rs = pstmt.executeQuery();
            while (rs.next()) {
                model.addRow(new Object[]{
                    rs.getString("maNVL"), rs.getString("tenNVL"),
                    rs.getString("loaiNVL"), rs.getInt("soLuong"), rs.getFloat("donGia")
                });
            }
            conn.close();
        } catch (Exception e) {
            e.printStackTrace();
        }
    }
   public void updateImage(String imagePath) {
    if (imagePath == null || imagePath.isEmpty()) {
        jLabel4.setIcon(null);
        jLabel4.setText("No Image");
        return;
    }
    
    ImageIcon myImage = new ImageIcon(imagePath);
    Image img = myImage.getImage();
    
    // Lấy kích thước của jLabel4. 
    // Nếu getWidth = 0 (do giao diện chưa load xong), ta đặt mặc định khoảng 150-200
    int width = jLabel4.getWidth() > 0 ? jLabel4.getWidth() : 180;
    int height = jLabel4.getHeight() > 0 ? jLabel4.getHeight() : 180;

    // ÉP ẢNH VỀ ĐÚNG KÍCH THƯỚC KHUNG
    Image newImg = img.getScaledInstance(width, height, Image.SCALE_SMOOTH);
    
    jLabel4.setIcon(new ImageIcon(newImg));
    jLabel4.setText(""); 
}

