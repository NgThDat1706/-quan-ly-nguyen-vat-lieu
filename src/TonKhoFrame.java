    private void btnTimKiemActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnTimKiemActionPerformed
        String name = txtTimKiem.getText().trim();
        if (name.isEmpty()) {
            loadData();
            return;
        }

        try {
            DefaultTableModel model = (DefaultTableModel) jTableTonKho.getModel();
            model.setRowCount(0);

            Connection conn = new DBContext().getConnection();
            // Dùng câu lệnh LIKE để tìm gần đúng tên
            String sql = "SELECT maNVL, tenNVL, soLuong FROM NGUYEN_VAT_LIEU WHERE tenNVL LIKE ?";
            PreparedStatement st = conn.prepareStatement(sql);
            st.setString(1, "%" + name + "%");
            ResultSet rs = st.executeQuery();

            while (rs.next()) {
                int sl = rs.getInt("soLuong");
                String tinhTrang = (sl < 10) ? "Cần nhập gấp!" : "An toàn";
                model.addRow(new Object[]{rs.getString(1), rs.getString(2), sl, tinhTrang});
            }
            conn.close();
        } catch (Exception e) {
            e.printStackTrace();
        }           // TODO add your handling code here:
    }//GEN-LAST:event_btnTimKiemActionPerformed

