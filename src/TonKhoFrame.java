    public void loadData() {
        try {
            // Lấy mô hình bảng và xóa dữ liệu cũ
            DefaultTableModel model = (DefaultTableModel) jTableTonKho.getModel();
            model.setRowCount(0);

            // Kết nối Database
            DBContext db = new DBContext();
            Connection conn = db.getConnection();

            // Câu lệnh lấy dữ liệu Tồn kho
            String sql = "SELECT maNVL, tenNVL, soLuong FROM NGUYEN_VAT_LIEU";
            Statement st = conn.createStatement();
            ResultSet rs = st.executeQuery(sql);

           while (rs.next()) {
    int sl = rs.getInt("soLuong"); // Lấy số lượng từ cột soLuong trong SQL
    
    // 1. Máy dùng Số Lượng để quyết định chữ Tình Trạng
    String tinhTrang = "";
    if (sl == 0) {
        tinhTrang = "HẾT HÀNG!";
    } else if (sl < 50) {
        tinhTrang = "Cần nhập gấp!";
    } else {
        tinhTrang = "An toàn";
    }

    // 2. Đưa vào bảng: Cột cuối cùng phải là biến tinhTrang
    model.addRow(new Object[]{
        rs.getString("maNVL"),   // Cột 1
        rs.getString("tenNVL"),  // Cột 2
        sl,                      // Cột 3 (Hiện con số)
        tinhTrang                // Cột 4 (Hiện chữ báo động dựa trên con số)
    });
}
            conn.close();
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Lỗi nạp dữ liệu: " + e.getMessage());
        }
    }

